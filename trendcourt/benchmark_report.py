def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
    return plt


def _save(fig, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150, bbox_inches="tight", metadata={"Software": None})


def _shade_real_cases(ax, fpr: dict) -> None:
    for var, (lo, hi) in real_case_ranges(fpr).items():
        ax.axvspan(lo, hi, color=VARIABLE_COLORS.get(var, "grey"), alpha=0.12, lw=0,
                   label=f"real cases: {var.replace('_', ' ')}")


def figure_fpr(fpr: dict, path: Path) -> None:
    """False-positive rate of Hamed–Rao against phi, one line per record length."""
    plt = _plt()
    years = fpr["grid"]["n_years"]
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.8), sharex=True)
    for ax, alpha in zip(axes, (0.05, 0.01)):
        _shade_real_cases(ax, fpr)
        for i, n in enumerate(years):
            cells = sorted((c for c in fpr["cells"] if c["n_years"] == n), key=lambda c: c["phi"])
            x = [c["phi"] + (i - 1) * 0.008 for c in cells]
            s = [c["rates"]["hamed_rao"][f"{alpha:g}"] for c in cells]
            y = [v["rate"] for v in s]
            err = [[v["rate"] - v["ci95"][0] for v in s], [v["ci95"][1] - v["rate"] for v in s]]
            ax.errorbar(x, y, yerr=err, marker="o", ms=4, capsize=2, lw=1.4, label=f"{n} years")
        ax.axhline(alpha, ls="--", color="black", lw=1, label="nominal level (alpha)")
        ax.set_title(f"Hamed–Rao, alpha = {alpha:g}")
        ax.set_xlabel("AR(1) phi of the noise")
        ax.set_ylim(bottom=0)
    axes[0].set_ylabel("false-positive rate (trend-free series)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=4, frameon=False, bbox_to_anchor=(0.5, -0.12))
    fig.suptitle(f"How often the test finds a trend that is not there "
                 f"({fpr['replicates']} replicates per point, exact 95% intervals)", y=1.0)
    _save(fig, path)
    plt.close(fig)


def figure_coverage(cov: dict, path: Path) -> None:
    """Theil–Sen 95% interval coverage against phi."""
    plt = _plt()
    phis = cov["grid"]["phi"]
    styles = dict(zip(cov["grid"]["slope_per_decade"], ("-", "--", ":")))
    fig, ax = plt.subplots(figsize=(6.5, 4.2))
    colors = plt.rcParams["axes.prop_cycle"].by_key()["color"]
    for i, n in enumerate(cov["grid"]["n_years"]):
        for slope, ls in styles.items():
            cells = sorted((c for c in cov["cells"] if c["n_years"] == n and c["slope_per_decade"] == slope),
                           key=lambda c: c["phi"])
            ax.plot([c["phi"] for c in cells], [c["coverage"]["rate"] for c in cells], ls=ls,
                    marker="o", ms=3, lw=1.1, color=colors[i],
                    label=f"{n} years, slope {slope:g} SD/decade")
    fine = [p / 100 for p in range(0, 91)]
    ax.plot(fine, [ar1_predicted_coverage(p) for p in fine], color="black", lw=2, alpha=0.35,
            label="predicted if the width ignores AR(1)")
    ax.axhline(cov["nominal"], ls="--", color="black", lw=1, label=f"nominal {cov['nominal']:.0%}")
    ax.set_xticks(phis)
    ax.set_ylim(0, 1)
    ax.set_xlabel("AR(1) phi of the noise")
    ax.set_ylabel("share of intervals containing the true slope")
    ax.set_title(f"Theil–Sen 95% interval coverage ({cov['replicates']} replicates per point)")
    ax.legend(fontsize=7, frameon=False, loc="lower left", ncol=2)
    _save(fig, path)
    plt.close(fig)


def figure_power(power: dict, fpr: dict, path: Path, alpha: float = 0.05) -> None:
    """Hamed–Rao power against record length, one line per slope, one panel per phi."""
    plt = _plt()
    phis = power["grid"]["phi"]
    fig, axes = plt.subplots(1, len(phis), figsize=(2.3 * len(phis), 3.4), sharey=True)
    key = f"{alpha:g}"
    for ax, phi in zip(axes, phis):
        for slope in power["grid"]["slope_per_decade"]:
            cells = sorted((c for c in power["cells"] if c["phi"] == phi and c["slope_per_decade"] == slope),
                           key=lambda c: c["n_years"])
            r = [c["rates"][key]["rejection"] for c in cells]
            x = [c["n_years"] for c in cells]
            line, = ax.plot(x, [v["rate"] for v in r], marker="o", ms=3, lw=1.3, label=f"{slope:g} SD/decade")
            ax.fill_between(x, [v["ci95"][0] for v in r], [v["ci95"][1] for v in r],
                            color=line.get_color(), alpha=0.15, lw=0)
        floor = thresholds.worst_fpr(fpr, phi, alpha)["rate"] if phi in fpr["grid"]["phi"] else None
        if floor is not None:
            ax.axhline(floor, ls=":", color="black", lw=1, label="rate on trend-free series")
        ax.set_title(f"phi = {phi:g}")
        ax.set_xlabel("record length (years)")
        ax.set_ylim(0, 1.02)
    axes[0].set_ylabel(f"rejection rate at alpha = {alpha:g}")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=5, frameon=False, bbox_to_anchor=(0.5, -0.1))
    fig.suptitle(f"Hamed–Rao power by record length, slope in noise SDs per decade "
                 f"({power['replicates']} replicates per point)", y=1.02)
    _save(fig, path)
    plt.close(fig)


def write_figures(results: dict, out_dir: Path = BENCH_DIR) -> list[Path]:
    paths = {k: out_dir / v for k, v in FIGURES.items()}
    figure_fpr(results["fpr"], paths["fpr"])
    figure_coverage(results["coverage"], paths["coverage"])
    figure_power(results["power"], results["fpr"], paths["power"])
    return list(paths.values())


