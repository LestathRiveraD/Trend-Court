"""Figures and tables for ``docs/benchmark.md``, from the committed benchmark JSON.

Nothing here reruns the simulation: every number comes from
``docs/benchmark/{fpr,coverage,power}.json`` (written by
``scripts/benchmark.py --experiment ...``) and
``trendcourt/thresholds.json``, except the no-trend columns of Table 6,
which read the committed real-case records in ``data/`` through
``clerk.prepare`` (:func:`real_case_no_trend`). Regenerate with::

    python scripts/benchmark.py --figures

which writes the three PNGs to ``docs/benchmark/`` and rewrites the block
between :data:`TABLES_START` and :data:`TABLES_END` in
``docs/benchmark.md``.
"""

from __future__ import annotations

import json
from pathlib import Path

from scipy.stats import norm

from trendcourt import thresholds

REPO_ROOT = Path(__file__).resolve().parents[1]
BENCH_DIR = REPO_ROOT / "docs" / "benchmark"
DOC_PATH = REPO_ROOT / "docs" / "benchmark.md"
FIGURES = {"fpr": "fpr_vs_phi.png", "coverage": "coverage_vs_phi.png", "power": "power_vs_years.png"}
TABLES_START = "<!-- tables:start (generated by scripts/benchmark.py --figures; do not edit) -->"
TABLES_END = "<!-- tables:end -->"

VARIABLE_COLORS = {"temperature": "#d95f02", "precipitation": "#1b9e77", "soil_moisture": "#7570b3"}
NOMINAL_Z = norm.ppf(0.975)


def load_results(bench_dir: Path = BENCH_DIR) -> dict:
    """The three committed experiment results, keyed ``fpr``, ``coverage``, ``power``."""
    return {k: json.loads((bench_dir / f"{k}.json").read_text(encoding="utf-8"))
            for k in ("fpr", "coverage", "power")}


def real_case_ranges(fpr: dict, key: str = "r1_detrended") -> dict[str, tuple[float, float]]:
    """Per variable, the (min, max) lag-1 autocorrelation of the real cases."""
    out: dict[str, list[float]] = {}
    for row in fpr["real_cases"]:
        if row[key] is not None:
            out.setdefault(row["variable"], []).append(row[key])
    return {v: (min(x), max(x)) for v, x in out.items()}


def ar1_predicted_coverage(phi: float, z: float = NOMINAL_Z) -> float:
    """Coverage of a nominal interval whose width ignores AR(1) noise:
    ``2 * Phi(z / f) - 1`` with ``f = thresholds.widening_factor(phi)``."""
    return float(2.0 * norm.cdf(z / thresholds.widening_factor(phi)) - 1.0)


def implied_widening(coverage: float, z: float = NOMINAL_Z) -> float:
    """Factor by which an interval with this coverage must widen to reach 95%,
    assuming a normal sampling distribution: ``z / Phi^-1((1 + coverage) / 2)``."""
    return float(z / norm.ppf((1.0 + coverage) / 2.0))


def _pooled_coverage(cov: dict, phi: float) -> float:
    cells = [c for c in cov["cells"] if c["phi"] == phi]
    return sum(c["coverage"]["k"] for c in cells) / sum(c["coverage"]["n"] for c in cells)


